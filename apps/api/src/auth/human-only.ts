import { ForbiddenException } from '@nestjs/common';
import { Request } from 'express';

// Ένα API key έχει ρόλο admin (jwt-auth.guard) αλλά δεν είναι άνθρωπος — το
// `sub` του είναι αρνητικό, κανενός χρήστη το id. Ό,τι δεν χρειάζεται καμία
// εξωτερική υπηρεσία μένει κλειστό σε αυτό:
//
// - διαχείριση κλειδιών, αλλιώς ένα κλειδί που διέρρευσε γεννάει διαδόχους και
//   η ανάκληση δεν τελειώνει ποτέ (σβήνεις μία γραμμή, ο επιτιθέμενος έχει δύο)·
// - οι χειρισμοί των μηχανημάτων (restart, kill session): το provisioning
//   φτιάχνει πελάτες και servers, δεν ρίχνει εκπομπές που παίζουν.
//
// Δεν είναι scopes — ένα κλειδί εξακολουθεί να μπορεί ό,τι κι ένας admin στα
// υπόλοιπα. Είναι το κόψιμο των δύο δρόμων που δεν έχουν καμία νόμιμη χρήση από
// υπηρεσία και είναι οι πιο ακριβοί όταν το κλειδί διαρρεύσει.
export function humanOnly(req: Request): void {
  if (req.user.sub < 0) {
    throw new ForbiddenException('δεν επιτρέπεται σε API key — μπες ως χρήστης');
  }
}
